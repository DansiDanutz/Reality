#!/usr/bin/env python3
"""
Reality HD asset generator — Nano Banana backend (Python).

Reads the prompt manifest JSON files produced by build-prompts.mjs, calls
Nano Banana (gemini-2.5-flash-image, aka Gemini 2.5 Flash Image) for each
prompt, saves the transparent PNG, and writes pending-review metadata.

BLOCKED until Nano Banana credentials are present:
  GEMINI_API_KEY  (or GOOGLE_API_KEY / GOOGLE_GENAI_API_KEY)

Loads .env.local automatically if present (Reality's gitignored env file).

When credentials are missing this script prints a blocker report and exits 0
WITHOUT calling any generator — per docs/plan/11-ASSET-GENERATION.md we do
not switch to a fallback generator.

Run:
  python3 assets/generated/reality/scripts/generate.py                 # all first-batch
  python3 assets/generated/reality/scripts/generate.py --only coffeeshop
  python3 assets/generated/reality/scripts/generate.py --dry-run
"""
from __future__ import annotations

import argparse
import base64
import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent  # assets/generated/reality
# scripts → reality → generated → assets → Reality: three parents from ROOT.
REPO_ROOT = ROOT.parent.parent.parent

MODEL = os.environ.get("NANO_BANANA_MODEL", "gemini-2.5-flash-image")


def load_dotenv_local() -> None:
    """Load ~/.env.local-style file at REPO_ROOT/.env.local into os.environ."""
    env_file = REPO_ROOT / ".env.local"
    if not env_file.exists():
        return
    for line in env_file.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key, value = key.strip(), value.strip().strip("'\"")
        # Skip values that still contain placeholder brackets (broken paste).
        if "<" in value or ">" in value:
            continue
        os.environ.setdefault(key, value)


def get_key() -> str | None:
    return (
        os.environ.get("GEMINI_API_KEY")
        or os.environ.get("GOOGLE_API_KEY")
        or os.environ.get("GOOGLE_GENAI_API_KEY")
    )


def load_targets(only: str | None) -> list[dict]:
    index = json.loads((ROOT / "prompts" / "manifest.json").read_text())
    targets = index["prompts"]
    if only:
        targets = [t for t in targets if t["assetId"] == only]
    return targets


def build_metadata(prompt_file: dict, source_png: str, metadata_path: str) -> dict:
    return {
        "assetId": prompt_file["assetId"],
        "kind": prompt_file["kind"],
        "sourceCodeId": prompt_file["assetId"].replace("dashboard-", "").replace("category-", ""),
        "sourceFile": (
            "src/components/hud/HudWindow.tsx"
            if prompt_file["kind"] == "dashboard-icon"
            else "src/game/catalog.ts"
        ),
        "category": (
            prompt_file["assetId"].replace("category-", "")
            if prompt_file["kind"] == "category-icon"
            else "dashboard" if prompt_file["kind"] == "dashboard-icon" else "(from catalog)"
        ),
        "uiPurpose": (
            prompt_file["prompt"].split("Purpose in game UI: ", 1)[1].split("\n", 1)[0]
            if "Purpose in game UI: " in prompt_file["prompt"]
            else ""
        ),
        "generator": "Nano Banana + rembg",
        "model": MODEL,
        "backgroundRemoval": "rembg u2net (local post-process; Nano Banana emits opaque RGB)",
        "prompt": prompt_file["prompt"],
        "negativePrompt": prompt_file["negativePrompt"],
        "sourcePng": source_png,
        "sourceSize": prompt_file["sourceSize"],
        "sourceFormat": "png",
        "runtimeFormats": ["png", "webp"],
        "camera": "slight top-down 3/4",
        "layers": ["base", "movable-part", "highlight", "shadow", "effect"],
        "variants": ["idle"],
        "qualityStatus": "pending-review",
        "qualityChecks": {
            "transparentBackground": False,
            "noEmbeddedText": False,
            "objectNotCropped": False,
            "readsAt64px": False,
            "cameraMatchesStandard": False,
            "lightingMatchesPalette": False,
            "shapeRecognizable": False,
            "partsSeparable": False,
            "variantsPreserveIdentity": False,
            "noExtraProps": False,
            "fileNameMatchesSourceId": True,
            "metadataPointsToSource": True,
        },
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "acceptedAt": None,
        "usageNotes": "Generated by Nano Banana. Awaiting quality-checklist review before runtime integration.",
    }


def generate_one(client, target: dict) -> bool:
    """Generate one asset. Returns True if generated, False if skipped (already exists)."""
    prompt_file = json.loads((ROOT / "prompts" / f"{target['assetId']}.json").read_text())
    out_png = REPO_ROOT / target["sourcePng"]
    out_png.parent.mkdir(parents=True, exist_ok=True)

    # Resume guard: skip assets already generated (PNG + metadata both present).
    # Lets the batch pick up where it left off after an interruption without
    # re-billing for completed work.
    meta_path = REPO_ROOT / prompt_file["metadataPath"]
    if out_png.exists() and meta_path.exists() and out_png.stat().st_size > 1000:
        print(f"  · {target['assetId']} already exists, skipping")
        return False

    # Nano Banana call: text -> image, response_modalities=["IMAGE"]
    response = client.models.generate_content(
        model=MODEL,
        contents=prompt_file["prompt"],
        config={"response_modalities": ["IMAGE"]},
    )

    parts = getattr(response.candidates[0].content, "parts", []) if response.candidates else []
    image_part = next((p for p in parts if getattr(p, "inline_data", None)), None)
    if image_part is None:
        raise RuntimeError(f"No image returned for {target['assetId']}")

    # The SDK returns raw image bytes in inline_data.data (already decoded
    # from the wire base64). Do NOT base64-decode again — write bytes directly.
    image_bytes = image_part.inline_data.data
    if isinstance(image_bytes, str):
        # Some SDK paths return a base64 string; handle defensively.
        image_bytes = base64.b64decode(image_bytes)

    # Nano Banana emits opaque RGB (no alpha channel) even when asked for
    # transparency — a known model limitation. Strip the background with rembg
    # (u2net, runs locally) to produce the transparent PNG the plan requires.
    # Imported lazily so the credential-gate path needs no rembg install.
    from rembg import remove
    transparent_bytes = remove(image_bytes)
    out_png.write_bytes(transparent_bytes)

    meta = build_metadata(prompt_file, target["sourcePng"], prompt_file["metadataPath"])
    meta_path = REPO_ROOT / prompt_file["metadataPath"]
    meta_path.parent.mkdir(parents=True, exist_ok=True)
    meta_path.write_text(json.dumps(meta, indent=2) + "\n")
    print(f"  ✓ {target['assetId']} → {target['sourcePng']} (pending review)")
    return True


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--only", default=None, help="Generate only this assetId")
    args = ap.parse_args()

    load_dotenv_local()
    key = get_key()

    targets = load_targets(args.only)
    if not targets:
        print(f"No prompts matched --only {args.only}", file=sys.stderr)
        return 1

    print(f"Nano Banana generation: {len(targets)} asset(s){' [DRY RUN]' if args.dry_run else ''}")

    if not key:
        print("╔" + "═" * 68 + "╗")
        print("║  NANO BANANA BLOCKED — no generation credentials present         ║")
        print("║  Checked env: GEMINI_API_KEY, GOOGLE_API_KEY, GOOGLE_GENAI_API_KEY ║")
        print("║  Per docs/plan/11-ASSET-GENERATION.md we do NOT switch generators. ║")
        print("║  Inventory, prompts, metadata schema, and runner are READY.       ║")
        print("╚" + "═" * 68 + "╝")
        return 0

    if args.dry_run:
        for t in targets:
            print(f"  would generate → {t['sourcePng']} ({t['sourceSize']})")
        return 0

    from google import genai  # imported here so the blocked path needs no deps
    client = genai.Client(api_key=key)

    ok = skip = fail = 0
    for t in targets:
        try:
            generated = generate_one(client, t)
            if generated:
                ok += 1
                time.sleep(2)  # Nano Banana throttles hard on the free tier
            else:
                skip += 1  # no API call — no throttle needed
        except Exception as e:
            print(f"  ✗ {t['assetId']}: {type(e).__name__}: {str(e)[:200]}")
            fail += 1
    print(f"\nDone: {ok} generated, {skip} skipped, {fail} failed. Review pending assets with the quality checklist.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
